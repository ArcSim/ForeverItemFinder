// The website's tooltips for old Classic items: the addon ships tooltips only for new and changed items (the game draws
// the rest), so the site gets the others here, from Forever's own client tables, in the addon's D.tips / D.effects /
// D.sets line formats. build_data.lua uses a line only when the addon has none for the item.
// usage: node build_classic_tips.js   (writes classic_tips.lua next to this file; never shipped in the addon)
const fs = require('fs');
const path = require('path');
const S = 'E:/WoWDev/projects/ArcDiscoveries/datamine/scripts';
const tt = require(`${S}/item_tooltip`);
const fx = require(`${S}/item_effects`);

const items = tt.loadItems(), tables = tt.loadTables(), extras = tt.loadExtras(), spells = fx.loadSpells();
const tips = [], effects = [], sets = new Map();
for (const [id, item] of [...items].sort((a, b) => a[0] - b[0])) {
	if (!item.name) continue;
	tips.push(`${id}|${tt.tipLine(tt.compute(item, tables), tt.details(item, id, spells, items, extras))}`);
	if (item.set && !sets.has(item.set)) sets.set(item.set, tt.setLine(item.set, spells, items, extras, fx.fillText));
	const lines = fx.itemLines(spells, id);
	if (lines.length) effects.push(`${id}|${fx.effectLine(lines)}`);
}
const setLines = [...sets].filter(([, v]) => v).sort((a, b) => a[0] - b[0]).map(([id, v]) => `${id}|${v}`);
const block = (name, lines) => {
	for (const l of lines) if (l.includes(']=]')) throw new Error(`${name}: a line holds the long-string closer`);
	return `${name} = [=[\n${lines.join('\n')}\n]=],\n`;
};
const out = path.join(__dirname, 'classic_tips.lua');
const text = `-- generated by build_classic_tips.js from Forever's client tables\nreturn {\n${block('tips', tips)}${block('effects', effects)}${block('sets', setLines)}}\n`;
fs.writeFileSync(out, text, 'utf8');
console.log(`tips ${tips.length}, effect lines ${effects.length}, sets ${setLines.length}; ${(Buffer.byteLength(text) / 1024).toFixed(0)} KB`);
